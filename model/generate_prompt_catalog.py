"""Generate C prompt-name lookup for MQTT from the SAME 41 text prompts.

Execute from repo root: python model/generate_prompt_catalog.py
No ML packages or model rebuilding required.
"""
from pathlib import Path
import argparse
from unidecode import unidecode


def c_quote(s: str) -> str:
    """Emit a C UTF-8 string using byte-safe octal escapes."""
    out = []
    for byte in s.encode("utf-8"):
        if byte == 34:
            out.append(r'\"')
        elif byte == 92:
            out.append(r'\\')
        elif byte == 10:
            out.append(r'\n')
        elif byte == 13:
            out.append(r'\r')
        elif 32 <= byte < 127:
            out.append(chr(byte))
        else:
            out.append(f"\\{byte:03o}")
    return '"' + ''.join(out) + '"'


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--repo-root", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--output", type=Path)
    args = parser.parse_args()
    ROOT = args.repo_root.resolve()
    MODEL = ROOT / "model"
    OUTPUT = args.output or (ROOT / "firmware" / "esp32s3" / "main" / "eco_prompt_catalog.h")
    prompts = [line.strip() for line in
               (MODEL / "prompts.txt").read_text(encoding="utf-8-sig").splitlines()
               if line.strip()]
    if len(prompts) != 41:
        raise SystemExit(f"Esperados 41 prompts, encontrados {len(prompts)}")

    manifest_file = MODEL / "text_embeddings.txt"
    if not manifest_file.exists():
        raise SystemExit("Falta model/text_embeddings.txt para validar a ordem dos prompts")
    manifest = [s.strip() for s in
                manifest_file.read_text(encoding="utf-8-sig").splitlines()
                if s.strip()]
    effective = [unidecode(p.lower().split(" - ")[-1]) for p in prompts]
    if effective != manifest:
        raise SystemExit("A ordem/texto de prompts.txt nao corresponde a text_embeddings.txt")

    # Present the same text description the model received, but keep normal case.
    labels = [p.split(" - ")[-1].strip() for p in prompts]
    if any(len(label.encode("utf-8")) > 180 for label in labels):
        raise SystemExit("Um prompt excede 180 bytes; reduza o tamanho do rotulo antes de publicar")
    header = [
        "// GENERATED by model/generate_prompt_catalog.py. Do not edit.",
        "#pragma once",
        "#define ECO_PROMPT_CATALOG_COUNT 41",
        "static const char *const eco_prompt_labels[ECO_PROMPT_CATALOG_COUNT] = {",
    ]
    header.extend(f"    {c_quote(s)}, // ID {i}" for i, s in enumerate(labels))
    header.append("};")
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text("\n".join(header) + "\n", encoding="utf-8")
    print(f"Catalogo criado: {OUTPUT} ({len(labels)} prompts)")


if __name__ == "__main__":
    main()
