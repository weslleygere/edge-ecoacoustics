"""Generate full 827x64 float32 Log-Mel reference for deterministic PCM16 input.

Run from repository root:
    python model/make_logmel_reference.py

The 64x513 Slaney weights are the exact binary weights embedded in ESP32-S3.
The input is deterministic white-noise PCM16 generated by xorshift32.
Only numpy is required. No WAV or inference is needed.
"""
from pathlib import Path
import hashlib
import numpy as np

ROOT = Path(__file__).resolve().parents[1]
MEL_PATH = ROOT / 'firmware/esp32s3/model/tinyclap_mel_filters.bin'
HEADER_PATH = ROOT / 'firmware/esp32s3/main/logmel_validation_reference.h'
N = 44100 * 6
FFT_SIZE = 1024
HOP = 320
FRAMES = N // HOP + 1
BANDS = 64
BINS = FFT_SIZE // 2 + 1


def synthetic_pcm():
    # Same uint32 wraparound arithmetic and int16 bit pattern as feature.c.
    state = 0x12345678
    values = np.empty(N, dtype=np.uint16)
    for i in range(N):
        state ^= (state << 13) & 0xFFFFFFFF
        state ^= state >> 17
        state ^= (state << 5) & 0xFFFFFFFF
        state &= 0xFFFFFFFF
        values[i] = (state >> 16) & 0xFFFF
    return values.view(np.int16)


def fnv1a(data: bytes):
    h = 2166136261
    for b in data:
        h = ((h ^ b) * 16777619) & 0xFFFFFFFF
    return h


def main():
    if not MEL_PATH.is_file():
        raise FileNotFoundError(f'Mel matrix missing: {MEL_PATH}')
    weights = np.fromfile(MEL_PATH, dtype='<f4')
    if weights.size != BANDS * BINS:
        raise ValueError(f'Expected {BANDS * BINS} mel float32 weights, got {weights.size}')
    weights = weights.reshape(BANDS, BINS).astype(np.float64)
    pcm = synthetic_pcm()
    # Match feature.c: int16 / 32768, reflect padding, periodic Hann.
    samples = pcm.astype(np.float64) / 32768.0
    padded = np.pad(samples, (FFT_SIZE // 2, FFT_SIZE // 2), mode='reflect')
    frames = np.lib.stride_tricks.sliding_window_view(padded, FFT_SIZE)[::HOP][:FRAMES]
    assert frames.shape == (FRAMES, FFT_SIZE), frames.shape
    hann = 0.5 - 0.5 * np.cos(2.0 * np.pi * np.arange(FFT_SIZE) / FFT_SIZE)
    spectrogram = np.fft.rfft(frames * hann, axis=1)
    powers = spectrogram.real ** 2 + spectrogram.imag ** 2
    energies = powers @ weights.T
    logmel = (10.0 * np.log10(np.maximum(energies, 1e-10))).astype('<f4')
    assert logmel.shape == (827, 64)
    words = logmel.ravel().view('<u4')
    lines = [
        '// Generated; do not edit. Python NumPy reference, exact embedded Mel matrix.\n',
        '#pragma once\n',
        '#include <stdint.h>\n',
        '#define LOGMEL_VALIDATION_ELEMENTS 52928u\n',
        'static const uint32_t kLogmelValidationReference[LOGMEL_VALIDATION_ELEMENTS] = {\n',
    ]
    for i in range(0, words.size, 12):
        lines.append('    ' + ', '.join(f'0x{int(w):08x}u' for w in words[i:i+12]) + ',\n')
    lines.append('};\n')
    HEADER_PATH.parent.mkdir(parents=True, exist_ok=True)
    HEADER_PATH.write_text(''.join(lines), encoding='ascii')
    print(f'VALIDATION PCM FNV1A={fnv1a(pcm.astype("<i2").tobytes()):08x} | first8={list(map(int, pcm[:8]))}')
    print(f'VALIDATION PYTHON LogMel | shape={logmel.shape} | min={logmel.min():.5f} | max={logmel.max():.5f} | mean={logmel.mean():.5f}')
    print(f'Mel SHA256={hashlib.sha256(MEL_PATH.read_bytes()).hexdigest()}')
    print(f'Generated: {HEADER_PATH}')


if __name__ == '__main__':
    main()
