"""Generate a desktop INT8 embedding reference for the ESP32-S3 test.

Run at the repository root:
    python model/make_tinyclap_reference.py

Creates firmware/esp32s3/main/validation_reference.h (1024 INT8 values).
Uses model_content instead of model_path to support Unicode Windows paths.
"""
from pathlib import Path
import hashlib
import numpy as np
from ai_edge_litert.interpreter import Interpreter

ROOT = Path(__file__).resolve().parents[1]
MODEL = ROOT / "firmware/esp32s3/model/tinyclap_phinet_int8.tflite"
ASSETS = ROOT / "firmware/esp32s3/model/tinyclap_text_assets.bin"
HEADER = ROOT / "firmware/esp32s3/main/validation_reference.h"


def fnv1a(raw):
    h = 2166136261
    for b in raw.view(np.uint8).ravel():
        h = ((h ^ int(b)) * 16777619) & 0xFFFFFFFF
    return h


def main():
    model = MODEL.read_bytes()
    print(f"Model file SHA256: {hashlib.sha256(model).hexdigest()}")
    print(f"Text assets SHA256: {hashlib.sha256(ASSETS.read_bytes()).hexdigest()}")
    intr = Interpreter(model_content=model, num_threads=1)
    intr.allocate_tensors()
    inp = intr.get_input_details()[0]
    out = intr.get_output_details()[0]
    assert tuple(inp["shape"]) == (1, 827, 64) and inp["dtype"] == np.int8
    assert tuple(out["shape"]) == (1, 1024) and out["dtype"] == np.int8
    i = np.arange(827 * 64, dtype=np.int64)
    q = (-100 + ((i * 37 + 13) % 160)).astype(np.int8).reshape(1, 827, 64)
    intr.set_tensor(inp["index"], q)
    intr.invoke()
    raw = intr.get_tensor(out["index"]).reshape(-1)
    assert raw.shape == (1024,)
    parts = [
        "// Generated by model/make_tinyclap_reference.py; validation-only.\n",
        "#pragma once\n",
        "#include <cstdint>\n",
        "static const int8_t kReferenceEmbedding[1024] = {\n",
    ]
    for pos in range(0, len(raw), 16):
        vals = ", ".join(str(int(x)) for x in raw[pos:pos + 16])
        parts.append("    " + vals + ",\n")
    parts.append("};\n")
    HEADER.parent.mkdir(parents=True, exist_ok=True)
    HEADER.write_text("".join(parts), encoding="ascii")
    print(f"VALIDATION FNV1A={fnv1a(raw):08x} | first8=" + ",".join(str(int(v)) for v in raw[:8]))
    print(f"Output quantization scale={out['quantization'][0]}, zero={out['quantization'][1]}")
    print(f"Reference header generated: {HEADER}")


if __name__ == "__main__":
    main()
